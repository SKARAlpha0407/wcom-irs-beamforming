"""Writes report/numbers.tex (LaTeX macros) from figures/results.json and copies
the figures and the simulator into report/ so that folder can be uploaded to Overleaf."""
import json
import os
import shutil

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "..", "figures")
REP = os.path.join(HERE, "..", "report")
R = json.load(open(os.path.join(FIG, "results.json")))

e1, e2 = R["exp1_power_vs_distance"], R["exp2_power_vs_N"]
e3, e4 = R["exp3_convergence"]["curves"], R["exp4_discrete_phase"]["curves"]
c, d = e1["curves"], e1["d"]
ao, lb = c["Alternating optimization"], c["Lower bound (SDR)"]
i15, i50 = d.index(15), d.index(50)
ipk = max(range(len(d)), key=lambda i: ao[i])
N = e2["N"]
ao50 = e2["curves"]["d=50"]["Alternating optimization"]
ao15 = e2["curves"]["d=15"]["Alternating optimization"]
ray = e3["Rayleigh (K = 0)"]


P = R["params"]
_L = 10 ** (P["C0_dB"] / 10) * np.hypot(50, P["dv"]) ** (-P["alpha_AU"])
no_irs_closed = 10 * np.log10(10 ** (P["gamma_dB"] / 10) * 10 ** ((P["noise_dBm"] - 30) / 10)
                              / ((P["M"] - 1) * _L)) + 30


no_irs_pl = 10 * np.log10(10 ** (P["gamma_dB"] / 10) * 10 ** ((P["noise_dBm"] - 30) / 10) / _L) + 30
# Values read from the vector data of the paper's figures (d = 50 m)
PAPER = {"noirs50": 19.19, "n20": 4.49, "n30": 1.49, "n60": -4.06}


def f(x, nd=1):
    s = f"{x:.{nd}f}"
    if float(s) == 0:
        return f"{0:.{nd}f}"
    # \\ensuremath gives a proper minus sign both in text and inside $...$
    return "\\ensuremath{" + s + "}" if s.startswith("-") else s


def small(x):
    """Gap that may be numerically ~0: print as 'less than 0.01' when tiny."""
    return "less than 0.01" if x < 0.01 else f(x, 2)


m = {
    "Msim": str(R["params"]["M"]),
    "Nsim": str(e1["N"]),
    "nReal": str(R["params"]["realisations"]),
    "nSdr": str(R["params"]["realisations_sdr"]),
    "nRand": str(R["params"]["randomisations"]),
    "peakD": str(d[ipk]),
    "peakP": f(ao[ipk]),
    "aoFifty": f(ao[i50]),
    "noIrsFifty": f(c["Without IRS"][i50]),
    "saveFifty": f(c["Without IRS"][i50] - ao[i50]),
    "gapLB": small(max(a - b for a, b in zip(ao, lb))),
    "gapUserMRT": f(c["AP-user MRT"][i50] - ao[i50]),
    "gapIrsMRT": f(c["AP-IRS MRT"][i15] - ao[i15]),
    "gapRand": f(c["Random phase shift"][i50] - ao[i50]),
    "dropA": f(ao50[N.index(40)] - ao50[N.index(80)]),
    "dropB": f(ao50[N.index(80)] - ao50[N.index(160)]),
    "dropFifteen": f(ao15[0] - ao15[-1]),
    "gapRay": small(ray["AO"][-1] - ray["lower_bound"]),
    "lossOne": f(e4["1-bit phase shifters"][-1] - e4["Alternating optimization"][-1]),
    "lossTwo": f(e4["2-bit phase shifters"][-1] - e4["Alternating optimization"][-1]),
    "aoNtwenty": f(ao50[N.index(20)]),
    "aoNthirty": f(ao50[N.index(30)]),
    "aoNsixty": f(ao50[N.index(60)]),
    # paper values read exactly from the vector data of its Fig. 3 and Fig. 4(a)
    "paperNoIrs": f(PAPER["noirs50"], 2),
    "paperNtwenty": f(PAPER["n20"], 2),
    "paperNthirty": f(PAPER["n30"], 2),
    "paperNsixty": f(PAPER["n60"], 2),
    "offNoIrs": f(PAPER["noirs50"] - c["Without IRS"][i50]),
    "offNtwenty": f(PAPER["n20"] - ao50[N.index(20)]),
    "offNthirty": f(PAPER["n30"] - ao50[N.index(30)]),
    "offNsixty": f(PAPER["n60"] - ao50[N.index(60)]),
    "dropPaper": f(ao50[N.index(30)] - ao50[N.index(60)]),
    "dropPaperFig": f(PAPER["n30"] - PAPER["n60"]),
    "closedNoIrs": f(no_irs_closed),
    "plNoIrs": f(no_irs_pl, 2),
    "offPl": f(PAPER["noirs50"] - no_irs_pl, 2),
    "gainLoS": f(e3["LoS (K = inf)"]["no_irs"] - e3["LoS (K = inf)"]["AO"][-1]),
    "gainRay": f(ray["no_irs"] - ray["AO"][-1]),
    "ciExpOne": f(max(e1["ci95_dB"]["AP-IRS MRT"]), 1),
    "ciExpOneRest": f(max(max(v) for k, v in e1["ci95_dB"].items() if k != "AP-IRS MRT"), 1),
    "ciExpTwo": f(max(max(v) for dd in e2["ci95_dB"].values() for v in dd.values()), 2),
    "lossThree": f(e4["3-bit phase shifters"][-1] - e4["Alternating optimization"][-1]),
}

cols = [15, 25, 35, 43, 47, 50]
names = [("Lower bound (SDR)", "Lower bound (SDR)"), ("SDR + randomization", "SDR + randomisation"),
         ("Alternating optimization", "Alternating optimisation"), ("AP-user MRT", "AP--user MRT"),
         ("AP-IRS MRT", "AP--IRS MRT"), ("Random phase shift", "Random phase shift"),
         ("Without IRS", "Without IRS")]
rows = [" & ".join([lab] + [f"${f(c[k][d.index(x)])}$" for x in cols]) + r" \\" for k, lab in names]
table = ("\\begin{tabular}{l" + "r" * len(cols) + "}\n\\toprule\nScheme & "
         + " & ".join(f"$d={x}$\\,m" for x in cols) + " \\\\\n\\midrule\n"
         + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")

with open(os.path.join(REP, "numbers.tex"), "w") as fh:
    fh.write("% Generated by simulation/make_numbers.py from figures/results.json. Do not edit by hand.\n")
    for k, v in m.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    fh.write("\\newcommand{\\tableDist}{%\n" + table + "}\n")

env = R["environment"]
rows_env = [("Python", env["python"]), ("NumPy", env["numpy"]), ("CVXPY", env["cvxpy"]),
            ("SCS (SDP solver)", env["scs"]), ("Matplotlib", env["matplotlib"]),
            ("Solver settings", env["solver"]), ("Operating system", env["os"]),
            ("Processor", env["cpu"]), ("Random seed", str(R["params"]["seed"]))]
tex_env = ("\\begin{tabular}{ll}\n\\toprule\nItem & Version / setting \\\\\n\\midrule\n"
           + "\n".join(f"{a} & {b} \\\\" for a, b in rows_env)
           + "\n\\bottomrule\n\\end{tabular}")
with open(os.path.join(REP, "numbers.tex"), "a") as fh:
    fh.write("\\newcommand{\\tableEnv}{%\n" + tex_env + "}\n")

os.makedirs(os.path.join(REP, "figures"), exist_ok=True)
for name in os.listdir(FIG):
    if name.endswith(".pdf"):
        shutil.copy(os.path.join(FIG, name), os.path.join(REP, "figures", name))
shutil.copy(os.path.join(HERE, "ris_sim.py"), os.path.join(REP, "ris_sim.py"))
print(json.dumps(m, indent=1))
